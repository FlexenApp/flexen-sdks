/**
 * Code generator: contract/snapshot.json -> TypeScript types and Pydantic v2 models.
 * Pure functions (snapshot in, source text out), so the drift check can regenerate in memory
 * and compare with the files in the repo.
 */

/** Schema names that would clash with built-ins in TypeScript (Error) get a different name in both SDKs. */
const RENAME = { Error: 'ErrorResponse', ErrorResponseError: 'ErrorDetail' }
const typeName = (n) => RENAME[n] ?? n
const pascal = (s) => s.replace(/(^|[_\-\s/{}]+)([a-zA-Z0-9])/g, (_, __, c) => c.toUpperCase())
const refName = (ref) => typeName(ref.replace('#/components/schemas/', ''))
const PY_KEYWORDS = new Set(['from', 'import', 'class', 'def', 'global', 'in', 'is', 'lambda', 'not', 'or', 'and', 'pass', 'return', 'with', 'yield', 'async', 'await', 'raise', 'try', 'while', 'for', 'if', 'else', 'elif', 'del', 'as', 'assert', 'break', 'continue', 'except', 'finally', 'nonlocal', 'None', 'True', 'False'])

/** Walks all schemas and returns named object types in a stable order, nested inline objects included. */
export function collectTypes(snapshot) {
  const out = [] // { name, schema, kind: 'object' | 'alias' }
  const visit = (name, schema) => {
    if (schema.type === 'object' || schema.properties) {
      out.push({ name, schema, kind: 'object' })
      for (const [prop, ps] of Object.entries(schema.properties ?? {})) {
        if (ps.type === 'object' && ps.properties) visit(typeName(`${name}${pascal(prop)}`), ps)
        if (ps.type === 'array' && ps.items?.type === 'object' && ps.items.properties) visit(typeName(`${name}${pascal(prop)}Item`), ps.items)
      }
    } else {
      out.push({ name, schema, kind: 'alias' })
    }
  }
  for (const [n, s] of Object.entries(snapshot.schemas)) visit(typeName(n), s)
  return out
}

/** Inline-object type name for a property, as collectTypes names it. */
function inlineName(parent, prop, schema) {
  if (schema.type === 'object' && schema.properties) return typeName(`${parent}${pascal(prop)}`)
  if (schema.type === 'array' && schema.items?.type === 'object' && schema.items.properties) return typeName(`${parent}${pascal(prop)}Item`)
  return null
}

/** Tiers of the operations that have them, by operationId. */
const tiersTable = (snapshot) => Object.fromEntries(snapshot.operations.filter((o) => o.tiers).map((o) => [o.operationId, o.tiers]))

// ---------------------------------------------------------------- TypeScript

function tsType(schema, parent, prop) {
  if (schema.$ref) return refName(schema.$ref)
  if (schema.oneOf) return schema.oneOf.map((s) => tsType(s, parent, prop)).join(' | ')
  if (schema.enum) return schema.enum.map((v) => JSON.stringify(v)).join(' | ')
  if (schema.const !== undefined) return JSON.stringify(schema.const)
  switch (schema.type) {
    case 'string':
      return 'string'
    case 'integer':
    case 'number':
      return 'number'
    case 'boolean':
      return 'boolean'
    case 'null':
      return 'null'
    case 'array': {
      const inner = schema.items?.type === 'object' && schema.items.properties ? inlineName(parent, prop, schema) : tsType(schema.items ?? {}, parent, prop)
      return inner.includes(' | ') ? `Array<${inner}>` : `${inner}[]`
    }
    case 'object':
      return schema.properties ? inlineName(parent, prop, schema) : 'Record<string, unknown>'
    default:
      return 'unknown'
  }
}

const tsDoc = (text, indent = '') => {
  if (!text) return ''
  const clean = String(text).replace(/\*\//g, '*\\/')
  return `${indent}/** ${clean} */\n`
}

const tsKey = (k) => (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(k) ? k : JSON.stringify(k))

function paramsTypeName(op) {
  return `${op.operationId[0].toUpperCase()}${op.operationId.slice(1)}Params`
}

export function generateTs(snapshot) {
  const L = []
  const src = snapshot.source
  L.push('/* eslint-disable */')
  L.push('// Generated by scripts/generate.mjs from contract/snapshot.json. Do not edit by hand.')
  L.push(`// Contract: ${src.repo} @ ${src.commit} (${src.files.join(', ')}), OpenAPI ${snapshot.info.version}.`)
  L.push('')
  L.push(`export const CONTRACT_SOURCE = ${JSON.stringify({ repo: src.repo, commit: src.commit, openapiVersion: snapshot.info.version })} as const`)
  L.push('')
  L.push('// ---------- Schemas (components.schemas) ----------')
  L.push('')
  for (const t of collectTypes(snapshot)) {
    const s = t.schema
    if (t.kind === 'alias') {
      L.push(tsDoc(s.description) + `export type ${t.name} = ${tsType(s, t.name, '')}`)
      L.push('')
      continue
    }
    const req = new Set(s.required ?? [])
    L.push(tsDoc(s.description) + `export interface ${t.name} {`)
    for (const [k, ps] of Object.entries(s.properties ?? {})) {
      L.push(tsDoc(ps.description, '  ') + `  ${tsKey(k)}${req.has(k) ? '' : '?'}: ${tsType(ps, t.name, k)}`)
    }
    if (s.additionalProperties === true) L.push('  [key: string]: unknown')
    L.push('}')
    L.push('')
  }
  L.push('// ---------- Parameters (path and query) per operation ----------')
  L.push('')
  for (const op of snapshot.operations) {
    if (op.parameters.length === 0) continue
    L.push(`/** Path and query parameters of ${op.method} ${op.path}. */`)
    L.push(`export interface ${paramsTypeName(op)} {`)
    for (const p of op.parameters) {
      L.push(tsDoc(`${p.description} (${p.in})`, '  ') + `  ${tsKey(p.name)}${p.required ? '' : '?'}: ${tsType(p.schema, paramsTypeName(op), p.name)}`)
    }
    L.push('}')
    L.push('')
  }
  L.push('// ---------- Operations ----------')
  L.push('')
  L.push(`export type OperationId = ${snapshot.operations.map((o) => JSON.stringify(o.operationId)).join(' | ')}`)
  L.push('')
  L.push('/** Request and response types per operation. */')
  L.push('export interface OperationTypes {')
  for (const op of snapshot.operations) {
    const params = op.parameters.length ? paramsTypeName(op) : 'undefined'
    const body = op.requestSchema ? typeName(op.requestSchema) : 'undefined'
    const res = op.responseSchema ? typeName(op.responseSchema) : 'unknown'
    L.push(`  ${op.operationId}: { params: ${params}; body: ${body}; response: ${res} }`)
  }
  L.push('}')
  L.push('')
  const opTable = Object.fromEntries(
    snapshot.operations.map((o) => [
      o.operationId,
      {
        id: o.id,
        method: o.method,
        path: o.path,
        state: o.state,
        credits: o.credits,
        pathParams: o.parameters.filter((p) => p.in === 'path').map((p) => p.name),
        queryParams: o.parameters.filter((p) => p.in === 'query').map((p) => p.name),
        hasBody: o.requestSchema !== null,
        errorStatuses: o.errorStatuses.map(Number),
      },
    ]),
  )
  L.push('/** Method, path, state and preliminary price (credits; null = open) of every operation in the contract. */')
  L.push(`export const OPERATIONS = ${JSON.stringify(opTable, null, 2)} as const`)
  L.push('')
  L.push("/** Endpoints the contract announces as 'later': not available, the SDK has no methods for them. */")
  L.push(`export const NOT_AVAILABLE = ${JSON.stringify(snapshot.unavailable, null, 2)} as const`)
  L.push('')
  L.push('// ---------- Errors, headers, limits ----------')
  L.push('')
  L.push(`export type ErrorCode = ${snapshot.errorCodes.map((c) => JSON.stringify(c.code)).join(' | ')}`)
  L.push('')
  L.push('/** Error codes with HTTP status and meaning, as in the contract. */')
  L.push(`export const ERROR_CODES = ${JSON.stringify(snapshot.errorCodes, null, 2)} as const`)
  L.push('')
  L.push(`export type ResponseHeaderName = ${snapshot.responseHeaders.map((h) => JSON.stringify(h.name)).join(' | ')}`)
  L.push('')
  L.push(`export const RESPONSE_HEADERS = ${JSON.stringify(snapshot.responseHeaders, null, 2)} as const`)
  L.push('')
  L.push('/** Limits per call (preliminary). Text length counts UTF-16 code units. imageMaxMiB applies to the decoded image. */')
  L.push(`export const LIMITS = ${JSON.stringify(snapshot.limits, null, 2)} as const`)
  L.push('')
  L.push(`export type TierId = ${snapshot.tierIds.map((t) => JSON.stringify(t)).join(' | ')}`)
  L.push(`export const DEFAULT_TIER = ${JSON.stringify(snapshot.defaultTier)} as const`)
  L.push(`export const TIER_IDS = ${JSON.stringify(snapshot.tierIds)} as const`)
  L.push("/** Tiers per AI operation. state 'later' = not available yet: with a live key the API answers 422 tier_unavailable (TierUnavailableError). */")
  L.push(`export const TIERS = ${JSON.stringify(tiersTable(snapshot), null, 2)} as const`)
  L.push('')
  L.push('/** prompt_version values the contract names today. */')
  L.push(`export const PROMPT_VERSION = ${JSON.stringify(snapshot.promptVersion, null, 2)} as const`)
  L.push('')
  return L.join('\n')
}

// ---------------------------------------------------------------- Python

function pyType(schema, parent, prop) {
  if (schema.$ref) return refName(schema.$ref)
  if (schema.oneOf) return schema.oneOf.map((s) => pyType(s, parent, prop)).join(' | ')
  if (schema.enum) return `Literal[${schema.enum.map((v) => JSON.stringify(v)).join(', ')}]`
  if (schema.const !== undefined) return `Literal[${pyLiteral(schema.const)}]`
  switch (schema.type) {
    case 'string':
      return 'str'
    case 'integer':
      return 'int'
    case 'number':
      return 'float'
    case 'boolean':
      return 'bool'
    case 'null':
      return 'None'
    case 'array': {
      const inner = schema.items?.type === 'object' && schema.items.properties ? inlineName(parent, prop, schema) : pyType(schema.items ?? {}, parent, prop)
      return `list[${inner}]`
    }
    case 'object':
      return schema.properties ? inlineName(parent, prop, schema) : 'dict[str, Any]'
    default:
      return 'Any'
  }
}

const pyStr = (s) => JSON.stringify(String(s))
const pyField = (k) => {
  let f = k.replace(/[^A-Za-z0-9_]/g, '_')
  if (PY_KEYWORDS.has(f) || /^model_/.test(f)) f = `${f}_`
  return f
}
const pyLiteral = (v) => JSON.stringify(v, null, 4).replace(/\btrue\b/g, 'True').replace(/\bfalse\b/g, 'False').replace(/\bnull\b/g, 'None')

export function generatePython(snapshot) {
  const L = []
  const src = snapshot.source
  L.push('# Generated by scripts/generate.mjs from contract/snapshot.json. Do not edit by hand.')
  L.push(`# Contract: ${src.repo} @ ${src.commit} (${src.files.join(', ')}), OpenAPI ${snapshot.info.version}.`)
  L.push('# ruff: noqa')
  L.push('from __future__ import annotations')
  L.push('')
  L.push('from typing import Any, Literal')
  L.push('')
  L.push('from pydantic import BaseModel, ConfigDict, Field')
  L.push('')
  L.push(`CONTRACT_SOURCE: dict[str, str] = ${pyLiteral({ repo: src.repo, commit: src.commit, openapiVersion: snapshot.info.version })}`)
  L.push('')
  L.push('')
  const types = collectTypes(snapshot)
  const models = []
  for (const t of types) {
    const s = t.schema
    if (t.kind === 'alias') {
      L.push(`${t.name} = ${pyType(s, t.name, '')}`)
      if (s.description) L.push(`"""${String(s.description).replace(/"""/g, '\\"\\"\\"')}"""`)
      L.push('')
      L.push('')
      continue
    }
    models.push(t.name)
    const extra = s.additionalProperties === false ? 'forbid' : 'allow'
    const req = new Set(s.required ?? [])
    L.push(`class ${t.name}(BaseModel):`)
    if (s.description) L.push(`    """${String(s.description).replace(/"""/g, '\\"\\"\\"')}"""`)
    L.push('')
    L.push(`    model_config = ConfigDict(extra=${pyStr(extra)}, populate_by_name=True, protected_namespaces=())`)
    L.push('')
    for (const [k, ps] of Object.entries(s.properties ?? {})) {
      const f = pyField(k)
      const ty = pyType(ps, t.name, k)
      const args = [req.has(k) ? '...' : 'None']
      if (f !== k) args.push(`alias=${pyStr(k)}`)
      if (ps.description) args.push(`description=${pyStr(ps.description)}`)
      L.push(`    ${f}: ${req.has(k) || / \| None$/.test(ty) ? ty : `${ty} | None`} = Field(${args.join(', ')})`)
    }
    if (Object.keys(s.properties ?? {}).length === 0) L.push('    pass')
    L.push('')
    L.push('')
  }
  L.push(`for _m in (${models.join(', ')},):`)
  L.push('    _m.model_rebuild()')
  L.push('')
  L.push('')
  L.push('#: Request model, response model and parameters (name, in, required) per operation.')
  const ops = {}
  for (const o of snapshot.operations) {
    ops[o.operationId] = {
      id: o.id,
      method: o.method,
      path: o.path,
      state: o.state,
      credits: o.credits,
      request: o.requestSchema ? typeName(o.requestSchema) : null,
      response: o.responseSchema ? typeName(o.responseSchema) : null,
      params: o.parameters.map((p) => [p.name, p.in, p.required]),
      error_statuses: o.errorStatuses.map(Number),
    }
  }
  L.push(`OPERATIONS: dict[str, dict[str, Any]] = ${pyLiteral(ops)}`)
  L.push('')
  L.push("#: Endpoints the contract announces as 'later': not available, the SDK has no methods for them.")
  L.push(`NOT_AVAILABLE: list[dict[str, Any]] = ${pyLiteral(snapshot.unavailable)}`)
  L.push('')
  L.push(`ErrorCode = Literal[${snapshot.errorCodes.map((c) => JSON.stringify(c.code)).join(', ')}]`)
  L.push('')
  L.push('#: Error codes with HTTP status and meaning, as in the contract.')
  L.push(`ERROR_CODES: list[dict[str, Any]] = ${pyLiteral(snapshot.errorCodes)}`)
  L.push('')
  L.push(`RESPONSE_HEADERS: list[dict[str, Any]] = ${pyLiteral(snapshot.responseHeaders)}`)
  L.push('')
  L.push('#: Limits per call (preliminary). Text length counts UTF-16 code units. imageMaxMiB applies to the decoded image.')
  L.push(`LIMITS: dict[str, Any] = ${pyLiteral(snapshot.limits)}`)
  L.push('')
  L.push(`TierId = Literal[${snapshot.tierIds.map((t) => JSON.stringify(t)).join(', ')}]`)
  L.push(`DEFAULT_TIER = ${JSON.stringify(snapshot.defaultTier)}`)
  L.push(`TIER_IDS: tuple[str, ...] = (${snapshot.tierIds.map((t) => JSON.stringify(t)).join(', ')},)`)
  L.push("#: Tiers per AI operation. state 'later' = not available yet: with a live key the API answers 422 tier_unavailable (TierUnavailableError).")
  L.push(`TIERS: dict[str, list[dict[str, Any]]] = ${pyLiteral(tiersTable(snapshot))}`)
  L.push('')
  L.push(`PROMPT_VERSION: dict[str, str] = ${pyLiteral(snapshot.promptVersion)}`)
  L.push('')
  L.push('MODELS: dict[str, type[BaseModel]] = {')
  for (const m of models) L.push(`    ${JSON.stringify(m)}: ${m},`)
  L.push('}')
  L.push('')
  return L.join('\n')
}

